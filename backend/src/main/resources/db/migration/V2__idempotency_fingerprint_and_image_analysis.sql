-- PostgreSQL과 테스트용 H2(PostgreSQL 모드)에서 모두 동작하는 문법만 사용한다.

-- 1) 같은 Idempotency-Key를 다른 내용에 재사용했는지 판단하기 위한 요청 지문(SHA-256, 16진수 64자).
--    V2 이전에 저장된 일정은 값이 없으며, 서버가 저장된 내용으로 다시 계산해 비교한다.
alter table events add column request_fingerprint varchar(64);

-- 2) AI 이미지 분석. 상태: pending → processing → needs_review → confirmed, 실패하면 failed(재시도 가능).
--    이미지 원본은 DB에 넣지 않고 ImageStorage가 돌려준 키만 저장한다.
create table image_analyses (
    id                 bigint generated by default as identity primary key,
    owner_id           bigint       not null references users (id),
    team_id            bigint references teams (id),
    status             varchar(20)  not null
        check (status in ('pending', 'processing', 'needs_review', 'failed', 'confirmed')),
    image_key          varchar(255) not null,
    image_content_type varchar(100) not null,
    image_size_bytes   bigint       not null,
    timezone           varchar(64)  not null,
    warnings           varchar(4000),
    failure_code       varchar(50),
    failure_message    varchar(500),
    attempt_count      integer      not null default 0,
    version            bigint       not null default 0,
    created_at         timestamp with time zone not null,
    updated_at         timestamp with time zone not null,
    confirmed_at       timestamp with time zone
);

create index idx_image_analyses_owner on image_analyses (owner_id);

-- 3) 분석 하나에서 나온 일정 후보. 날짜·시간은 AI가 읽은 그대로(검증 전 문자열) 보관하고,
--    확정할 때 실제 달력·시간 검증을 통과한 후보만 events에 저장한다.
--    materials·uncertain_fields·warnings는 JSON 문자열 배열이다.
create table analysis_candidates (
    id               bigint generated by default as identity primary key,
    analysis_id      bigint      not null references image_analyses (id),
    position         integer     not null,
    title            varchar(200),
    start_date       varchar(32),
    start_time       varchar(16),
    end_date         varchar(32),
    end_time         varchar(16),
    timezone         varchar(64) not null,
    location         varchar(255),
    materials        varchar(2000),
    description      varchar(2000),
    recurring        boolean     not null default false,
    recurrence_note  varchar(255),
    uncertain_fields varchar(1000),
    warnings         varchar(2000),
    event_id         bigint references events (id),
    created_at       timestamp with time zone not null,
    updated_at       timestamp with time zone not null,
    constraint uq_analysis_candidates_position unique (analysis_id, position)
);
