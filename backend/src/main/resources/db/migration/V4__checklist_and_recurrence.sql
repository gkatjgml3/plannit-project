-- 1) 준비물. 일정마다 여러 항목을 순서대로 저장한다. 팀 일정이면 팀원 모두 같은 목록을 본다.
--    수정할 때 목록 전체를 지우고 다시 넣으므로 (event_id, sort_order)에 고유 제약을 두지 않는다.
create table event_checklist_items (
    id         bigint generated by default as identity primary key,
    event_id   bigint       not null references events (id),
    content    varchar(200) not null,
    sort_order integer      not null,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null
);

create index idx_event_checklist_items_event on event_checklist_items (event_id, sort_order);

-- 2) 반복 규칙. 원본 일정 한 행에만 저장하고, 회차는 조회할 때 timezone 기준으로 펼친다(행으로 복사하지 않음).
--    recurrence_until은 일정 timezone 기준 날짜(그날 포함), recurrence_by_days는 WEEKLY 요일("MO,WE,FR").
alter table events add column recurrence_frequency varchar(10);
alter table events add column recurrence_interval integer;
alter table events add column recurrence_until date;
alter table events add column recurrence_count integer;
alter table events add column recurrence_by_days varchar(27);

alter table events add constraint chk_events_recurrence check (
    (recurrence_frequency is null and recurrence_interval is null and recurrence_until is null
        and recurrence_count is null and recurrence_by_days is null)
    or (recurrence_frequency in ('DAILY', 'WEEKLY', 'MONTHLY') and recurrence_interval >= 1
        and not (recurrence_until is not null and recurrence_count is not null))
);

-- 3) 분석 후보의 반복 규칙. AI가 읽은 값을 그대로(검증 전) 보관하고 확정할 때 검증한다.
alter table analysis_candidates add column recurrence_frequency varchar(16);
alter table analysis_candidates add column recurrence_interval integer;
alter table analysis_candidates add column recurrence_until varchar(32);
alter table analysis_candidates add column recurrence_count integer;
alter table analysis_candidates add column recurrence_by_days varchar(64);
