-- PostgreSQL과 테스트용 H2(PostgreSQL 모드)에서 모두 동작하는 문법만 사용한다.

create table users (
    id            bigint generated by default as identity primary key,
    email         varchar(255) not null unique,
    password_hash varchar(255) not null,
    name          varchar(100) not null,
    created_at    timestamp with time zone not null,
    updated_at    timestamp with time zone not null
);

create table teams (
    id         bigint generated by default as identity primary key,
    name       varchar(100) not null,
    created_by bigint       not null references users (id),
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null
);

create table team_members (
    team_id   bigint      not null references teams (id),
    user_id   bigint      not null references users (id),
    role      varchar(20) not null check (role in ('OWNER', 'MEMBER')),
    joined_at timestamp with time zone not null,
    primary key (team_id, user_id)
);

create index idx_team_members_user on team_members (user_id);

-- team_id가 null이면 개인 일정, 값이 있으면 팀 일정이다.
-- 팀 일정은 팀원마다 복사하지 않고 이 테이블에 한 행만 저장한다.
create table events (
    id          bigint generated by default as identity primary key,
    team_id     bigint references teams (id),
    created_by  bigint       not null references users (id),
    title       varchar(200) not null,
    starts_at   timestamp with time zone not null,
    ends_at     timestamp with time zone not null,
    timezone    varchar(64)  not null,
    description varchar(2000),
    location    varchar(255),
    version     bigint       not null default 0,
    created_at  timestamp with time zone not null,
    updated_at  timestamp with time zone not null,
    deleted_at  timestamp with time zone,
    -- 같은 요청이 두 번 저장되지 않도록 Idempotency-Key 헤더 값을 보관한다.
    request_id  varchar(100),
    constraint chk_events_time_range check (ends_at > starts_at),
    constraint uq_events_request unique (created_by, request_id)
);

create index idx_events_team_starts on events (team_id, starts_at);
create index idx_events_creator_starts on events (created_by, starts_at);

create table event_user_settings (
    event_id      bigint  not null references events (id),
    user_id       bigint  not null references users (id),
    hidden        boolean not null default false,
    reminder_at   timestamp with time zone,
    personal_memo varchar(2000),
    primary key (event_id, user_id)
);
