-- 알림 outbox. 일정 변경과 같은 트랜잭션에서 행을 쌓고, 스케줄러가 발송 시각이 지난 PENDING 행을 처리한다.
-- scheduled_at: 원래 발송 예정 시각, next_attempt_at: 다음 시도 시각(재시도하면 뒤로 밀린다).
-- 여러 서버가 동시에 처리해도 SELECT ... FOR UPDATE SKIP LOCKED로 한 행을 한 서버만 가져간다.
create table notification_outbox (
    id              bigint generated by default as identity primary key,
    user_id         bigint      not null references users (id),
    kind            varchar(30) not null
        check (kind in ('EVENT_REMINDER', 'TEAM_EVENT_CREATED', 'TEAM_EVENT_UPDATED', 'TEAM_EVENT_DELETED')),
    event_id        bigint      not null references events (id),
    scheduled_at    timestamp with time zone not null,
    next_attempt_at timestamp with time zone not null,
    status          varchar(20) not null check (status in ('PENDING', 'SENT', 'FAILED', 'CANCELED')),
    attempt_count   integer     not null default 0,
    last_error      varchar(100),
    sent_at         timestamp with time zone,
    read_at         timestamp with time zone,
    created_at      timestamp with time zone not null,
    updated_at      timestamp with time zone not null
);

create index idx_notification_outbox_due on notification_outbox (status, next_attempt_at);
create index idx_notification_outbox_user on notification_outbox (user_id, scheduled_at);
create index idx_notification_outbox_event on notification_outbox (event_id);
